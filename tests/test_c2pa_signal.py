import dataclasses
from pathlib import Path

import pytest

from talax import Context, State
from talax.model import C2paReport
from talax.provenance import read_c2pa
from talax.signals import C2paCredentials


def evaluate(ctx: Context, report: C2paReport | None) -> tuple[State, str]:
    result = C2paCredentials().evaluate(dataclasses.replace(ctx, c2pa=report))
    return result.state, result.explanation


def intact(**overrides: object) -> C2paReport:
    base: dict[str, object] = {
        "present": True,
        "state": "Valid",
        "codes": ("signingCredential.untrusted",),
        "signer": "Example Camera Co",
        "signed_at": "2026-01-01T10:00:00+00:00",
        "generator": "ExampleCam 1.0",
    }
    return C2paReport(**{**base, **overrides})  # type: ignore[arg-type]


def test_not_read(ctx: Context) -> None:
    assert evaluate(ctx, None)[0] is State.UNVERIFIABLE


def test_absent_says_absence_means_nothing(ctx: Context) -> None:
    state, text = evaluate(ctx, C2paReport(present=False))
    assert state is State.UNVERIFIABLE
    assert "says nothing" in text


def test_read_error(ctx: Context) -> None:
    state, text = evaluate(ctx, C2paReport(present=True, error="boom"))
    assert state is State.UNVERIFIABLE
    assert "boom" in text


def test_trusted_and_intact_is_consistent(ctx: Context) -> None:
    state, text = evaluate(ctx, intact(state="Trusted", codes=()))
    assert state is State.CONSISTENT
    assert "Example Camera Co" in text


def test_intact_but_untrusted_signer_is_to_check(ctx: Context) -> None:
    state, text = evaluate(ctx, intact())
    assert state is State.TO_CHECK
    assert "cannot be confirmed" in text


@pytest.mark.parametrize(
    "code", ["claimSignature.mismatch", "assertion.hashedURI.mismatch"]
)
def test_tampered_credentials_are_suspicious(ctx: Context, code: str) -> None:
    state, _ = evaluate(ctx, intact(state="Invalid", codes=(code,)))
    assert state is State.SUSPICIOUS


def test_image_changed_after_signing_is_to_check(ctx: Context) -> None:
    state, text = evaluate(
        ctx, intact(state="Invalid", codes=("assertion.dataHash.mismatch",))
    )
    assert state is State.TO_CHECK
    assert "after signing" in text


def test_tampering_wins_over_content_change(ctx: Context) -> None:
    codes = ("assertion.dataHash.mismatch", "claimSignature.mismatch")
    assert evaluate(ctx, intact(state="Invalid", codes=codes))[0] is State.SUSPICIOUS


def test_ai_declaration_is_reported(ctx: Context) -> None:
    _, text = evaluate(ctx, intact(ai_declared=True))
    assert "generated by AI" in text


def test_never_uses_banned_vocabulary(ctx: Context) -> None:
    reports = [
        intact(state="Trusted", codes=()),
        intact(),
        intact(state="Invalid", codes=("claimSignature.mismatch",)),
    ]
    for report in reports:
        text = evaluate(ctx, report)[1].lower()
        assert "certified" not in text and "authentic" not in text


def test_file_without_credentials(tmp_path: Path) -> None:
    path = tmp_path / "plain.jpg"
    path.write_bytes(
        b"\xff\xd8\xff\xe0\x00\x10JFIF\x00\x01\x01\x00\x00\x01\x00\x01\x00\x00\xff\xd9"
    )
    report = read_c2pa(path)
    assert report.present is False


def test_unreadable_file_never_raises(tmp_path: Path) -> None:
    path = tmp_path / "garbage.jpg"
    path.write_bytes(b"not an image at all")
    report = read_c2pa(path)
    assert report.present is False
