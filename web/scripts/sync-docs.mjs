// Brings what the front needs from the repository's docs/ folder, which stays
// the only source: Angular cannot read files outside web/. Runs before every
// build, dev server and test run (see package.json). The output is not versioned.
//
// - docs/brand: logo and favicons, copied into public/.
// - docs/legal: terms of use and privacy policy, Markdown turned into HTML here,
//   at build time, so that no Markdown library reaches the browser.
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Marked } from 'marked';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const docs = join(web, '..', 'docs');

// --- Brand -------------------------------------------------------------------
const brand = join(web, 'public', 'brand');
rmSync(brand, { recursive: true, force: true });
mkdirSync(brand, { recursive: true });
for (const file of readdirSync(join(docs, 'brand'))) {
  if (file.endsWith('.svg')) copyFileSync(join(docs, 'brand', file), join(brand, file));
}
for (const file of ['favicon.svg', 'favicon.ico']) {
  copyFileSync(join(docs, 'brand', file), join(web, 'public', file));
}

// --- Legal pages -------------------------------------------------------------
function legalPage(source) {
  const marked = new Marked({
    renderer: {
      // Links between the documents point to the pages of the site.
      link({ href, tokens }) {
        const text = this.parser.parseInline(tokens);
        const page = /^(terms|privacy)\.(en|fr)\.md$/.exec(href)?.[1];
        if (page) return `<a href="/${page}">${text}</a>`;
        return `<a href="${href}" rel="noopener">${text}</a>`;
      },
    },
  });
  const tokens = marked.lexer(source);
  const title = tokens.find((token) => token.type === 'heading' && token.depth === 1);
  const draft = tokens.find((token) => token.type === 'blockquote');
  const body = tokens.filter((token) => token !== title && token !== draft);
  body.links = tokens.links;
  return {
    title: title?.text ?? '',
    draft: draft ? marked.parser(draft.tokens) : '',
    // The sections, in order: the page finds them by position (Angular's
    // sanitizer removes ids from inserted HTML).
    toc: body
      .filter((token) => token.type === 'heading' && token.depth === 2)
      .map((token) => token.text),
    html: marked.parser(body),
  };
}

const legal = {};
for (const page of ['terms', 'privacy']) {
  legal[page] = {};
  for (const lang of ['en', 'fr']) {
    legal[page][lang] = legalPage(readFileSync(join(docs, 'legal', `${page}.${lang}.md`), 'utf8'));
  }
}
const generated = join(web, 'src', 'generated');
mkdirSync(generated, { recursive: true });
writeFileSync(
  join(generated, 'legal.ts'),
  `// Generated by scripts/sync-docs.mjs from docs/legal/. Do not edit.\n` +
    `import type { LegalPages } from '../app/features/legal/legal-page';\n\n` +
    `export const LEGAL_PAGES: LegalPages = ${JSON.stringify(legal, null, 2)};\n`,
);
