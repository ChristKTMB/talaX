// Brings what the front needs from the repository's docs/ folder, which stays
// the only source: Angular cannot read files outside web/. Runs before every
// build, dev server and test run (see package.json). The output is not versioned.
//
// - docs/brand: logo and favicons, copied into public/.
// - docs/legal and docs/guide: terms of use, privacy policy and user guide,
//   Markdown turned into HTML here,
//   at build time, so that no Markdown library reaches the browser.
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Marked } from 'marked';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const docs = join(web, '..', 'docs');
const { paths } = JSON.parse(readFileSync(join(web, 'src/app/core/i18n/pages.json'), 'utf8'));

// --- Brand -------------------------------------------------------------------
const brand = join(web, 'public', 'brand');
rmSync(brand, { recursive: true, force: true });
mkdirSync(brand, { recursive: true });
for (const file of readdirSync(join(docs, 'brand'))) {
  if (file.endsWith('.svg')) copyFileSync(join(docs, 'brand', file), join(brand, file));
}
for (const file of ['favicon.svg', 'favicon.ico', 'og-en.png', 'og-fr.png']) {
  copyFileSync(join(docs, 'brand', file), join(web, 'public', file));
}

// --- Documents: legal pages and user guide -----------------------------------
// Source file (in docs/) -> page name (in pages.json).
const DOCUMENTS = {
  'legal/terms': 'terms',
  'legal/privacy': 'privacy',
  'guide/site': 'guide',
  'guide/cli': 'guide-cli',
  'guide/report': 'guide-report',
};

/** The page a link to another document points to, or null. */
function linkedPage(href, from) {
  const match = /^(?:\.\.\/(legal|guide)\/)?([a-z]+)\.(en|fr)\.md$/.exec(href);
  if (!match) return null;
  const folder = match[1] ?? from;
  return DOCUMENTS[`${folder}/${match[2]}`] ?? null;
}

function documentPage(source, lang, folder) {
  const marked = new Marked({
    renderer: {
      // Links between the documents point to the pages of the site, in the
      // document's language.
      link({ href, tokens }) {
        const text = this.parser.parseInline(tokens);
        const page = linkedPage(href, folder);
        if (page) return `<a href="${paths[page][lang]}">${text}</a>`;
        return `<a href="${href}" rel="noopener">${text}</a>`;
      },
    },
  });
  const tokens = marked.lexer(source);
  const title = tokens.find((token) => token.type === 'heading' && token.depth === 1);
  // Only a legal text can be a draft not yet in force.
  const draft = folder === 'legal' && tokens.find((token) => token.type === 'blockquote');
  const body = tokens.filter((token) => token !== title && token !== draft);
  body.links = tokens.links;
  return {
    title: title?.text ?? '',
    draft: draft ? marked.parser(draft.tokens) : '',
    // The sections, in order: the page finds them by position (Angular's
    // sanitizer removes ids from inserted HTML).
    toc: body
      .filter((token) => token.type === 'heading' && token.depth === 2)
      // Plain text: Markdown marks (`code`, **bold**) stay out of the list.
      .map((token) => token.text.replace(/[`*]/g, '')),
    html: marked.parser(body),
  };
}

const documents = {};
for (const [file, page] of Object.entries(DOCUMENTS)) {
  const folder = file.split('/')[0];
  documents[page] = {};
  for (const lang of ['en', 'fr']) {
    documents[page][lang] = documentPage(
      readFileSync(join(docs, `${file}.${lang}.md`), 'utf8'),
      lang,
      folder,
    );
  }
}
const generated = join(web, 'src', 'generated');
mkdirSync(generated, { recursive: true });
// Written by earlier versions of this script (legal pages only).
rmSync(join(generated, 'legal.ts'), { force: true });
writeFileSync(
  join(generated, 'documents.ts'),
  `// Generated by scripts/sync-docs.mjs from docs/legal/ and docs/guide/. Do not edit.\n` +
    `import type { Documents } from '../app/features/legal/legal-page';\n\n` +
    `export const DOCUMENTS: Documents = ${JSON.stringify(documents, null, 2)};\n`,
);
